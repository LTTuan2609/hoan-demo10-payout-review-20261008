 console.log('PASS UI rejected withdrawal: refund to wallet and ledger credit');
 await goto('/payout/edit');
 await page.locator('select[name=bank_code]').selectOption('TCB');
 await page.locator('input[name=account_number]').fill('0123456789');
 await page.locator('input[name=account_holder]').fill('NGUYEN VAN A');
 await page.locator('form[data-form=payout] button.primary').click();
 await page.waitForURL(/#\/payout$/,{timeout:8000});
 const manager=await page.locator('main').innerText();
