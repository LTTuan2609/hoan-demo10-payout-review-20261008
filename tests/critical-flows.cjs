 await page.locator('form[data-form=payout] button.primary').click();
 await page.waitForURL(/#\/payout$/,{timeout:8000});
 assert.ok((await page.locator('main').innerText()).includes('••••4567'),'MoMo card missing');
 console.log('PASS UI MoMo account save and masked output');
 await goto('/');await page.locator('#shop-link').fill('https://example.com/evil');
 await page.locator('[role=alert].inline-error').waitFor({timeout:7500});
 assert.equal(await page.locator('.inline-product').count(),0,'Invalid link generated product');
